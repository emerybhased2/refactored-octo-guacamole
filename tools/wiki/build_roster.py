#!/usr/bin/env python3
"""Adds the wiki-sourced animals (those missing from data/progression/animals.json) with provenance. Idempotent. Run from the repo root."""
import json,re,subprocess,sys
ROOT='.'
W=json.load(open('data/research/wiki-animals.json'))['animals']
A=json.load(open('data/progression/animals.json')); have={a['id']:a for a in A}
abil={a['id'] for a in json.load(open('data/abilities/abilities.json'))}
colors=json.loads(subprocess.check_output(['node','-e',"""
global.window=global; global.MopeArt=require('./tools/art/draw.js'); require('./tools/art/specs.js'); const N=require('./tools/art/specs2.js'); const o={}; for (const k in N) o[k]=N[k].color||null; console.log(JSON.stringify(o));"""],text=True))
VERSION_DATE='2026-11-13'
SKIP={'Lion/Lion Cub','Lion/Lioness','Giraffe/White Giraffe','Lemming (tier 1)','Bullet Ant','Dolphin','Chipmunk (food)','Mouse (food)','Animals','Effects','Species'}
ALIAS={'crocodile':'croc','blackwidowspider':'blackwidow','komododragon':'komodo','giantscorpion':'scorpion'}
norm=lambda n: re.sub(r'[^a-z]','',n.lower())
BIOME={'Land':'land','Arctic':'arctic','Ocean':'ocean','Desert':'desert','Volcano':'volcano','Forest':'forest','Deep Ocean':'deepocean','Underground':'underground'}
KW=[('pull from hole','pull_from_hole'),('stomp','stomp'),('extra boost','extra_boost'),('claw slash','claw_slash'),('spin web','spin_web'),('fire','fire'),('charge','charge'),('disguise','disguise'),('venom','venom_spit'),('jaw bite','jaws_bite'),('slide on ice','slide_on_ice'),('whirlpool','whirlpool'),('hide in shell','shell'),('inflate','inflate'),('ink','ink'),('shock','shock'),('tail slap','tail_slap'),('trunk','trunk_hit'),('fly with prey','fly_with_prey'),('cause wave','cause_wave'),('arm smash','arm_smash'),('stink','stink'),('camouflage','camouflage'),('throw spear','throw_spear'),('dig food','dig_for_food'),('dig hole','burrow_hole'),('suffocate','suffocate_prey'),('bite drag','bite_drag'),('freeze','freeze'),('growl','growl'),('howl','howl')]
def kw(text):
    t=(text or '').lower()
    for k,i in KW:
        if k in t and i in abil: return i
    return None
def xp(s):
    m=re.match(r'([\d.,]+)\s*([KMB]?)',s or '');
    if not m: return None
    return int(float(m.group(1).replace(',',''))*{'':1,'K':1000,'M':10**6,'B':10**9}[m.group(2)])
bytier={}
for a in A: bytier.setdefault(a['tier'],a)
def stat(tier,k):
    a=bytier.get(tier) or bytier[min(bytier,key=lambda t:abs(t-tier))]; return a[k]
added=[]
for page,r in W.items():
    if page in SKIP: continue
    i=ALIAS.get(norm(page),norm(page))
    if i in have: continue
    if not r['tier'].isdigit(): continue
    tier=int(r['tier']); biome=BIOME.get(r['biome'])
    if not biome: continue
    x=xp(r.get('fromXp')) or xp(r.get('minXp')) or stat(tier,'xpRequired')
    col=colors.get(i)
    a={"id":i,"internalId":None,"name":page,"aliases":[],"tier":tier,"biome":biome,"xpRequired":x,"health":100,"speed":stat(tier,'speed'),"size":stat(tier,'size'),"damage":10,"ability":kw(r['special']),
       "sprite":f"assets/animals/2026-wiki/{i}.png","spriteStatus":"recreated","spriteNote":"Original artwork in the Mope.io style generated by tools/art (not Mope.io's own art).","placeholderColor":col or "#888888","description":"",
       "releaseDate":VERSION_DATE if not r['unreleased'] else "2099-01-01","removalDate":None,"classification":(["unreleased"] if r['unreleased'] else []),
       "unreleased":r['unreleased'],"wiki":page,"wikiReleased":r['releasedDates'],"wikiRemoved":r['removedDates'],"abilityText":r['special'],"passiveText":r['passive'],
       "confidence":{"existence":"verified (Mope.io Wiki page)","name":"verified (wiki)","internalId":"unknown","color":"inferred (original art)","ability":"wiki text; mapping to an implemented ability is "+("direct" if kw(r['special']) else "none"),"biome":"wiki","tier":"wiki","xp":"wiki ("+("upgrade threshold" if r.get('fromXp') else "minimum XP" if r.get('minXp') else "tier-typical, inferred")+")","stats":"inferred"},
       "evidence":f"Mope.io Wiki '{page}': tier {tier}, {r['biome']}"+(", unreleased" if r['unreleased'] else ""),
       "releaseDateNote":"Added to this project in the wiki-sourced version "+VERSION_DATE+"; the animal's own release dates on the wiki are in wikiReleased."}
    added.append(a)
missing_art=[a['id'] for a in added if a['id'] not in colors]
print(len(added),'animals to add; no spec for:',missing_art)
if '--write' in sys.argv:
    ids={a['id'] for a in A}
    for a in added:
        if a['id'] not in ids: A.append(a)
    json.dump(A,open('data/progression/animals.json','w'),indent=2); print('written',len(A))
